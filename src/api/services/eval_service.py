PROJECT_ROOT = Path(__file__).parent.parent.parent.parent  # nanoCursor root
EVALS_DIR = PROJECT_ROOT / "evals"
EVAL_TASKS_DIR = EVALS_DIR / "tasks"
EVAL_FIXTURES_DIR = EVALS_DIR / "fixtures"


def load_eval_tasks() -> list[dict[str, Any]]:
    """Load eval tasks from evals/tasks/*.json, merged with STARTER_EVALS."""
    tasks: dict[str, dict[str, Any]] = {e["id"]: dict(e) for e in STARTER_EVALS}
    if EVAL_TASKS_DIR.exists():
        for task_file in sorted(EVAL_TASKS_DIR.glob("*.json")):
            try:
                data = json.loads(task_file.read_text(encoding="utf-8"))
                if data.get("id"):
                    tasks[data["id"]] = data
            except (json.JSONDecodeError, OSError):
                continue
    return list(tasks.values())


def get_eval_task(eval_id: str) -> dict[str, Any] | None:
    """Get a single eval task definition."""
    for task in load_eval_tasks():
        if task["id"] == eval_id:
            return task
    return None


def prepare_eval_workspace(eval_id: str, workspace_dir: str | None = None) -> Path:
    """Copy fixture to a temporary eval workspace."""
    task = get_eval_task(eval_id)
    if not task:
        raise ValueError(f"Eval 任务不存在: {eval_id}")

    fixture_name = task.get("fixture", "")
    fixture_dir = EVAL_FIXTURES_DIR / fixture_name
    if not fixture_dir.exists() or not fixture_name:
        raise ValueError(f"Eval fixture 不存在: {fixture_name}")

    base_workspace = _workspace(workspace_dir) if workspace_dir is not None else _workspace()
    eval_ws = base_workspace / ".nanocursor" / "eval_workspaces" / f"{eval_id}-{int(time.time() * 1000)}"
    if eval_ws.exists():
        shutil.rmtree(eval_ws)
    shutil.copytree(fixture_dir, eval_ws)
    return eval_ws


def score_eval_run(thread_id: str, workspace_dir: str, signals: dict[str, Any]) -> dict[str, Any]:
    """Score a real eval run by reading events, session, diff, delivery from disk.

    R6 enhanced metrics: completion, test pass, delivery, risk, tool calls,
    file writes, duration, approval, recovery.
    """
    store = get_event_store()
    events = store.list_events(thread_id, workspace_dir)
    session = store.get_session(thread_id, workspace_dir)
    ws_str = str(workspace_dir)
    checks: list[dict[str, Any]] = []
    event_types = {e.type for e in events}

    # 1. required_events
    required = signals.get("required_events", [])
    missing = [r for r in required if r not in event_types]
    checks.append({
        "id": "required_events",
        "label": "必需事件",
        "status": "passed" if not missing else "failed",
        "detail": f"缺失: {missing}" if missing else "全部存在",
    })

    # 2. tests_pass
    if signals.get("tests_pass"):
        test_events = [e for e in events if e.type == "test_finished"]
        passed = any(
            isinstance(e.payload, dict) and e.payload.get("status") == "passed"
            for e in test_events
        ) if test_events else bool(test_events)
        checks.append({
            "id": "tests_pass",
            "label": "测试通过",
            "status": "passed" if passed else "failed",
            "detail": f"{len(test_events)} 个测试事件",
        })

    # 3. max_changed_files
    max_files = signals.get("max_changed_files")
    if max_files is not None:
        file_events = [e for e in events if e.type == "file_changed"]
        changed = len({e.payload.get("path", "") for e in file_events if isinstance(e.payload, dict)}) or len(file_events)
        checks.append({
            "id": "max_changed_files",
            "label": f"修改文件 ≤ {max_files}",
            "status": "passed" if changed <= max_files else "failed",
            "detail": f"实际 {changed} 个",
        })

    # 4. forbidden_paths
    forbidden = signals.get("forbidden_paths", [])
    if forbidden:
        file_events = [e for e in events if e.type == "file_changed"]
        violated = [
            e.payload.get("path", "") for e in file_events
            if isinstance(e.payload, dict) and any(f in e.payload.get("path", "") for f in forbidden)
        ]
        checks.append({
            "id": "forbidden_paths",
            "label": "禁止修改路径",
            "status": "passed" if not violated else "failed",
            "detail": f"违规: {violated}" if violated else "无违规",
        })

    # 5. required_files
    required_files = signals.get("required_files", [])
    if required_files:
        ws_path = Path(workspace_dir)
        missing_files = [f for f in required_files if not (ws_path / f).exists()]
        checks.append({
            "id": "required_files",
            "label": "必需文件存在",
            "status": "passed" if not missing_files else "failed",
            "detail": f"缺失: {missing_files}" if missing_files else "全部存在",
        })

    # ---- R6 enhanced metrics ----

    # Completion
    session_status = session.get("status", "unknown") if session else "unknown"
    checks.append({
        "id": "run_completed",
        "label": "运行已完成",
        "status": "passed" if session_status == "completed" else "failed",
        "detail": f"状态: {session_status}",
    })

    # Tool call count
    tool_events = [e for e in events if e.type == "tool_call_finished"]
    checks.append({
        "id": "tool_calls",
        "label": "工具调用次数",
        "status": "passed" if len(tool_events) > 0 else "warning",
        "detail": f"{len(tool_events)} 次",
    })

    # File writes
    file_events = [e for e in events if e.type == "file_changed"]
    checks.append({
        "id": "file_writes",
        "label": "文件写入次数",
        "status": "passed" if len(file_events) > 0 else "warning",
        "detail": f"{len(file_events)} 个文件",
    })

    # Delivery generated
    delivery_exists = False
    try:
        from src.api.services.delivery_service import load_delivery_contract
        dc = load_delivery_contract(thread_id, ws_str)
        delivery_exists = dc is not None
    except Exception:
        pass
    checks.append({
        "id": "delivery_generated",
        "label": "交付契约已生成",
        "status": "passed" if delivery_exists else "warning",
        "detail": "已生成" if delivery_exists else "未生成",
    })

    # Error events
    error_events = [e for e in events if e.type == "error"]
    checks.append({
        "id": "no_errors",
        "label": "无运行时错误",
        "status": "passed" if not error_events else "failed",
        "detail": f"{len(error_events)} 个错误" if error_events else "无错误",
    })

    passed = sum(1 for c in checks if c["status"] == "passed")
    failed = sum(1 for c in checks if c["status"] == "failed")
    warning = sum(1 for c in checks if c["status"] == "warning")

    return {
        "thread_id": thread_id,
        "overall": "passed" if failed == 0 else "failed",
        "passed_count": passed,
        "failed_count": failed,
        "warning_count": warning,
        "checks": checks,
        "event_count": len(events),
        "tool_call_count": len(tool_events),
        "file_write_count": len(file_events),
        "error_count": len(error_events),
        "session_status": session_status,
        "delivery_generated": delivery_exists,
    }


def compare_eval_runs(eval_id: str, limit: int = 10) -> dict[str, Any]:
    """Return historical eval results for trend comparison."""
    workspace = _workspace()
    evals_root = _evals_root(workspace)
    runs: list[dict[str, Any]] = []
    if evals_root.exists():
        for run_dir in sorted(evals_root.iterdir(), key=lambda d: d.stat().st_mtime, reverse=True):
            result_file = run_dir / "result.json"
            if not result_file.exists():
                continue
            try:
                result = json.loads(result_file.read_text(encoding="utf-8"))
                if result.get("eval_id") == eval_id:
                    runs.append(result)
            except (json.JSONDecodeError, OSError):
                continue
            if len(runs) >= limit:
                break

    passed_runs = sum(1 for r in runs if r.get("score", {}).get("overall") == "passed")
    return {
        "eval_id": eval_id,
        "total_runs": len(runs),
        "passed": passed_runs,
        "failed": len(runs) - passed_runs,
        "pass_rate": round(passed_runs / max(len(runs), 1), 2),
        "recent_runs": runs[:10],
    }


