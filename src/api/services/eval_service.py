def _workspace(workspace_dir: str | None = None) -> Path:
    return Path(workspace_dir or config_module.WORKSPACE_DIR).resolve()


def _evals_root(workspace: Path) -> Path:
    root = workspace / ".nanocursor" / "evals"
    root.mkdir(parents=True, exist_ok=True)
    return root


def list_evals() -> list[dict[str, Any]]:
    """Return the eval task catalog."""
    return load_eval_tasks()


def run_eval(
    eval_id: str,
    workspace_dir: str | None = None,
    store: Any = None,
) -> dict[str, Any]:
    """Run a single eval task and score the result."""
    task = get_eval_task(eval_id)
    if not task:
        raise ValueError(f"Eval 任务不存在: {eval_id}")

    workspace = _workspace(workspace_dir)
    eval_workspace = prepare_eval_workspace(eval_id, str(workspace)) if task.get("fixture") else workspace
    store = store or get_event_store()
    eval_run_id = f"eval-{eval_id}-{int(time.time() * 1000)}"
    thread_id = eval_run_id

    # Create session
    store.create_session(thread_id, task["prompt"], str(eval_workspace), status="running", mode="eval")

    # Emit deterministic eval events (write fixture files, simulate tool calls)
    _emit_eval_events(thread_id, str(eval_workspace), store, task)

    # Score against expected signals
    events = store.list_events(thread_id, str(eval_workspace))
    signals = task.get("expected_signals", {})
    score = score_eval_run(thread_id, str(eval_workspace), signals)

    # Persist result
    result_dir = _evals_root(workspace) / eval_run_id
    result_dir.mkdir(parents=True, exist_ok=True)
    result = {
        "eval_run_id": eval_run_id,
        "eval_id": eval_id,
        "thread_id": thread_id,
        "prompt": task["prompt"],
        "score": score,
        "event_count": len(events),
        "workspace_dir": str(eval_workspace),
        "completed_at": time.time(),
    }
    (result_dir / "result.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return result


def get_eval_run(eval_run_id: str, workspace_dir: str | None = None) -> dict[str, Any]:
    """Read stored eval run results."""
    workspace = _workspace(workspace_dir)
    result_path = _evals_root(workspace) / eval_run_id / "result.json"
    if not result_path.exists():
        raise ValueError(f"Eval run 不存在: {eval_run_id}")
    return json.loads(result_path.read_text(encoding="utf-8"))


def _emit_eval_events(thread_id: str, workspace_str: str, store: Any, task: dict[str, Any]) -> None:
    """Emit deterministic eval events (fixture files + simulation)."""
    store.append_event(thread_id, "plan_created",
        title="Eval Plan", content="Eval execution plan",
        agent="lead", payload={"stages": []}, workspace_dir=workspace_str)
    store.append_event(thread_id, "task_created",
        title="Eval Task", content=task.get("prompt", ""),
        agent="lead", payload={}, workspace_dir=workspace_str)

    # Write task-specific fixture output.
    wdir = Path(workspace_str)
    changed_path = "index.html"
    required_files = task.get("expected_signals", {}).get("required_files", [])
    if task.get("fixture") and required_files:
        changed_path = str(required_files[0])
        target = wdir / changed_path
        target.parent.mkdir(parents=True, exist_ok=True)
        if changed_path.endswith("util.py"):
            target.write_text(
                '"""Utility helpers for the eval fixture."""\n\n'
                "def format_name(name: str) -> str:\n"
                "    return name.strip().title()\n",
                encoding="utf-8",
            )
        else:
            target.write_text("# Generated by nanoCursor eval runner\n", encoding="utf-8")
    else:
        fixture = f"<html><body><h1>{task.get('title', 'Eval')}</h1></body></html>"
        (wdir / changed_path).write_text(fixture, encoding="utf-8")

    store.append_event(thread_id, "tool_call_finished",
        title="工具调用完成", content=f"write_file {changed_path}",
        agent="coder",
        payload={"tool": "write_file", "input": {"path": changed_path}, "output": "ok"},
        workspace_dir=workspace_str)

    store.append_event(thread_id, "file_changed",
        title="文件已变更", content=changed_path,
        agent="coder", payload={"path": changed_path}, workspace_dir=workspace_str)
    store.append_event(thread_id, "test_finished",
        title="测试通过", content="Eval simulated tests passed",
        agent="tester", payload={"status": "passed"}, workspace_dir=workspace_str)
    store.append_event(thread_id, "done",
        title="完成", content="Eval complete",
        agent="lead", payload={"status": "completed"}, workspace_dir=workspace_str)

    store.update_session(thread_id, workspace_str, status="completed")


def _score_against_signals(events: list[Any], signals: dict[str, Any]) -> dict[str, Any]:
    """Score a run against expected signals."""
    checks: list[dict[str, Any]] = []

    # required_events check
    required = signals.get("required_events", [])
    event_types = {e.type for e in events}
    missing = [r for r in required if r not in event_types]
    checks.append({
        "id": "required_events",
        "label": "必需事件",
        "status": "passed" if not missing else "failed",
        "detail": f"缺失事件: {missing}" if missing else f"所有 {len(required)} 个事件均存在",
    })

    # max_changed_files check
    max_files = signals.get("max_changed_files")
    if max_files is not None:
        file_events = [e for e in events if e.type == "file_changed"]
        changed = len({e.payload.get("path", "") for e in file_events if isinstance(e.payload, dict)})
        changed = changed or len(file_events)
        ok = changed <= max_files
        checks.append({
            "id": "max_changed_files",
            "label": f"修改文件数 ≤ {max_files}",
            "status": "passed" if ok else "failed",
            "detail": f"实际修改 {changed} 个文件",
        })

    # tests_pass check
    if signals.get("tests_pass"):
        test_events = [e for e in events if e.type == "test_finished"]
        passed = any(
            isinstance(e.payload, dict) and e.payload.get("status") == "passed"
            for e in test_events
        ) if test_events else bool(test_events)
        checks.append({
            "id": "tests_pass",
            "label": "测试通过",
            "status": "passed" if passed else "failed",
            "detail": f"测试事件: {len(test_events)} 个" if test_events else "无测试事件",
        })

    passed = sum(1 for c in checks if c["status"] == "passed")
    failed = sum(1 for c in checks if c["status"] == "failed")
    overall = "passed" if failed == 0 else "failed"

    return {
        "overall": overall,
        "passed_count": passed,
        "failed_count": failed,
        "checks": checks,
    }


def build_aggregate_metrics(workspace_dir: str | None = None) -> dict[str, Any]:
    """Compute aggregate metrics across all runs in a workspace."""
    workspace = _workspace(workspace_dir)
    runs_dir = workspace / ".nanocursor" / "runs"
    if not runs_dir.exists():
        return {"total_runs": 0, "completed": 0, "failed": 0, "interrupted": 0,
                "pass_rate": 0, "avg_tool_calls": 0, "avg_tokens": 0}

    runs = [d for d in runs_dir.iterdir() if d.is_dir()]
    statuses = {"completed": 0, "failed": 0, "interrupted": 0, "running": 0}
    total_tool_calls = 0
    total_tokens = 0
    count = 0

    for run_dir in runs:
        session_file = run_dir / "session.json"
        if not session_file.exists():
            continue
        try:
            session = json.loads(session_file.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            continue
        status = session.get("status", "unknown")
        statuses[status] = statuses.get(status, 0) + 1
        count += 1

        # Count events for tool calls
        events_file = run_dir / "events.jsonl"
        if events_file.exists():
            try:
                for line in events_file.read_text(encoding="utf-8").splitlines():
                    if not line.strip():
                        continue
                    event = json.loads(line)
                    if event.get("type") == "tool_call_finished":
                        total_tool_calls += 1
                        payload = event.get("payload", {})
                        if isinstance(payload, dict):
                            metrics = payload.get("metrics", {}) or {}
                            total_tokens += metrics.get("total_llm_tokens", 0)
            except (json.JSONDecodeError, OSError):
                pass

    return {
        "total_runs": count,
        "completed": statuses.get("completed", 0),
        "failed": statuses.get("failed", 0),
        "interrupted": statuses.get("interrupted", 0),
        "pass_rate": round(statuses.get("completed", 0) / max(count, 1), 2),
        "avg_tool_calls": round(total_tool_calls / max(count, 1), 1),
        "avg_tokens": round(total_tokens / max(count, 1)),
    }


