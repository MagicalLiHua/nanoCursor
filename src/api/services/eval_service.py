def get_eval_artifacts(eval_run_id: str, workspace_dir: str | None = None) -> dict[str, Any]:
    """Return all artifacts for an eval run: events, delivery, changes, failures."""
    workspace = _workspace(workspace_dir)
    result = get_eval_run(eval_run_id, str(workspace))
    thread_id = result.get("thread_id", eval_run_id)
    eval_ws = result.get("workspace_dir", str(workspace))

    store = get_event_store()
    events_raw = store.list_events(thread_id, eval_ws)
    events = [
        {"type": e.type, "title": e.title, "content": str(e.content)[:200], "agent": e.agent}
        for e in events_raw
    ]

    delivery = None
    try:
        from src.api.services.delivery_service import load_delivery_contract
        dc = load_delivery_contract(thread_id, eval_ws)
        if dc:
            delivery = dc.model_dump()
    except Exception:
        pass

    changes = None
    try:
        from src.api.services.change_service import load_change_set
        cs = load_change_set(thread_id, eval_ws)
        if cs:
            changes = cs.model_dump()
    except Exception:
        pass

    failures = None
    try:
        from src.api.services.failure_classifier_service import load_failures
        fl = load_failures(thread_id, eval_ws)
        if fl:
            failures = [f.model_dump() for f in fl]
    except Exception:
        pass

    return {
        "eval_run_id": eval_run_id,
        "thread_id": thread_id,
        "score": result.get("score"),
        "events": events,
        "event_count": result.get("event_count", len(events)),
        "delivery": delivery,
        "changes": changes,
        "failures": failures,
    }


def compare_eval_runs_detailed(eval_run_a: str, eval_run_b: str, workspace_dir: str | None = None) -> dict[str, Any]:
    """Detailed side-by-side comparison of two eval runs."""
    workspace = _workspace(workspace_dir)

    result_a = get_eval_run(eval_run_a, str(workspace))
    result_b = get_eval_run(eval_run_b, str(workspace))

    def _extract(r):
        if not r:
            return {}
        score = r.get("score", {})
        return {
            "eval_run_id": r.get("eval_run_id", ""),
            "overall": score.get("overall", ""),
            "passed_count": score.get("passed_count", 0),
            "failed_count": score.get("failed_count", 0),
            "event_count": score.get("event_count", 0),
            "tool_call_count": score.get("tool_call_count", 0),
            "error_count": score.get("error_count", 0),
            "delivery_generated": score.get("delivery_generated", False),
        }

    return {
        "run_a": _extract(result_a),
        "run_b": _extract(result_b),
        "delta": {
            "passed": (_extract(result_b).get("passed_count", 0) - _extract(result_a).get("passed_count", 0)),
            "tool_calls": (_extract(result_b).get("tool_call_count", 0) - _extract(result_a).get("tool_call_count", 0)),
            "errors": (_extract(result_b).get("error_count", 0) - _extract(result_a).get("error_count", 0)),
        },
    }
